// Generate src/core/text_emb_data.h - the hard-coded text embedding table.
//
//   node tools/gen_emb.mjs
//
// Reads  seedvr2_videoupscaler/pos_emb.f32 / neg_emb.f32  (which are produced
// once from the original pos_emb.pt / neg_emb.pt, bfloat16) and emits the table
// as `inline const double` so the embeddings can be compiled into the binary.
//
// All paths are resolved relative to this file, so it can be run from anywhere.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SRC = path.join(ROOT, 'seedvr2_videoupscaler');
const OUT = path.join(ROOT, 'src/core/text_emb_data.h');

// raw dump format: "SEEDVR2EMB1" + int64 rows + int64 cols + float32 data
function readF32(p) {
  const b = fs.readFileSync(p);
  const magic = b.subarray(0, 11).toString('latin1');
  if (magic !== 'SEEDVR2EMB1') throw new Error('bad magic in ' + p + ': ' + JSON.stringify(magic));
  const rows = Number(b.readBigInt64LE(11));
  const cols = Number(b.readBigInt64LE(19));
  const n = rows * cols;
  const dv = new DataView(b.buffer, b.byteOffset + 27, n * 4);
  const out = new Float64Array(n);
  for (let i = 0; i < n; i++) out[i] = dv.getFloat32(i * 4, true);
  return { rows, cols, data: out };
}

function emitArray(name, arr, perLine) {
  const parts = [];
  parts.push(`inline const double ${name}[${arr.length}] = {`);
  let line = '';
  for (let i = 0; i < arr.length; i++) {
    // shortest decimal that round-trips through float32, stored as double
    let s = Number(arr[i]).toPrecision(9);
    if (s.indexOf('e') < 0 && s.indexOf('.') >= 0) s = s.replace(/0+$/, '').replace(/\.$/, '');
    if (s === '-0') s = '0';
    line += s + ',';
    if ((i + 1) % perLine === 0) { parts.push(line); line = ''; }
  }
  if (line) parts.push(line);
  parts.push('};');
  return parts.join('\n');
}

const pos = readF32(path.join(SRC, 'pos_emb.f32'));
const neg = readF32(path.join(SRC, 'neg_emb.f32'));

const hdr = `// Auto-generated by tools/gen_emb.mjs - do not edit.
// Hard-coded text embeddings (originally pos_emb.pt / neg_emb.pt, bfloat16,
// converted losslessly to f32 and stored here as double).  Encoding the values
// in the binary removes the runtime dependency on the external .pt/.f32 files.
#pragma once

namespace seedvr2 {

static const int kPosEmbRows = ${pos.rows};
static const int kPosEmbCols = ${pos.cols};
static const int kNegEmbRows = ${neg.rows};
static const int kNegEmbCols = ${neg.cols};

${emitArray('kPosEmb', pos.data, 12)}

${emitArray('kNegEmb', neg.data, 12)}

} // namespace seedvr2
`;

fs.writeFileSync(OUT, hdr);
console.log('wrote', OUT, hdr.length, 'bytes');
console.log('pos', pos.rows + 'x' + pos.cols, 'neg', neg.rows + 'x' + neg.cols);
